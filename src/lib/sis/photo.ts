// Photo handling that must not depend on the browser: content sniffing and
// limits. The browser also resizes the image before upload, but the server never
// trusts the declared file type or size.

export const PHOTO_BUCKET = "student-photos";
export const PHOTO_MAX_BYTES = 800 * 1024;

export type PhotoType = { mime: "image/jpeg" | "image/png" | "image/webp"; ext: "jpg" | "png" | "webp" };

export function detectPhotoType(bytes: Uint8Array): PhotoType | null {
  if (bytes.length >= 3 && bytes[0] === 0xff && bytes[1] === 0xd8 && bytes[2] === 0xff) {
    return { mime: "image/jpeg", ext: "jpg" };
  }
  if (
    bytes.length >= 8 &&
    bytes[0] === 0x89 && bytes[1] === 0x50 && bytes[2] === 0x4e && bytes[3] === 0x47 &&
    bytes[4] === 0x0d && bytes[5] === 0x0a && bytes[6] === 0x1a && bytes[7] === 0x0a
  ) {
    return { mime: "image/png", ext: "png" };
  }
  if (
    bytes.length >= 12 &&
    bytes[0] === 0x52 && bytes[1] === 0x49 && bytes[2] === 0x46 && bytes[3] === 0x46 &&
    bytes[8] === 0x57 && bytes[9] === 0x45 && bytes[10] === 0x42 && bytes[11] === 0x50
  ) {
    return { mime: "image/webp", ext: "webp" };
  }
  return null;
}

// Object names are generated by the server; this guards anything read back from
// the database before it is used as a Storage path.
export function isSafePhotoPath(path: string): boolean {
  return /^[A-Za-z0-9][A-Za-z0-9._-]{4,119}$/.test(path) && !path.includes("..");
}
